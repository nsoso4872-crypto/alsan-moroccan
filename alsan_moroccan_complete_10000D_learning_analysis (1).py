def تحليل_التجارب_واقتراح_التحسينات():
    """تحليل وصفي بسيط لسجل التجارب؛ لا يغيّر الكود أو النموذج تلقائياً."""
    التجارب = تحميل_تجارب_عِلسان()
    print("\n🇲🇦 عِلسان — تحليل التجارب واقتراح التحسينات")
    if not التجارب:
        print("مازال ما كايناش تجارب محفوظة. سجّل تجربة أولاً من الخيار 26.")
        return

    عدد_التجارب = len(التجارب)
    نتائج_فارغة = sum(1 for ت in التجارب if not str(ت.get("النتيجة", "")).strip())
    ملاحظات_فارغة = sum(1 for ت in التجارب if not str(ت.get("الملاحظة", "")).strip())
    كلمات_النجاح = ("نجح", "ناجح", "نجاح", "تم بنجاح")
    عدد_النجاحات = sum(
        1 for ت in التجارب
        if any(ك in str(ت.get("النتيجة", "")) for ك in كلمات_النجاح)
    )

    print(f"عدد التجارب المحفوظة: {عدد_التجارب}")
    print(f"نتائج غير مكتوبة: {نتائج_فارغة}")
    print(f"ملاحظات فارغة: {ملاحظات_فارغة}")
    print(f"نتائج فيها كلمات كتدل على النجاح: {عدد_النجاحات}")
    print("\nالدروس المسجلة:")
    for رقم, تجربة in enumerate(التجارب, start=1):
        اسم = str(تجربة.get("اسم_التجربة", "بلا اسم"))
        نتيجة = str(تجربة.get("النتيجة", ""))
        ملاحظة = str(تجربة.get("الملاحظة", ""))
        print(f"{رقم}. {اسم}: {ملاحظة or نتيجة or 'ما تسجّل حتى درس.'}")

    print("\nاقتراحات للتحسين:")
    if نتائج_فارغة:
        print("- كمّل النتائج الناقصة فالتجارب المقبلة.")
    if ملاحظات_فارغة:
        print("- سجّل ملاحظة قصيرة: شنو خدم وشنو خاصو يتحسّن.")
    if عدد_التجارب < 3:
        print("- سجّل جوج تجارب إضافية على الأقل قبل ما نستنتجو نمطاً من النتائج.")
    else:
        print("- قارن النتائج المتشابهة، وعاود الاختبارات باش تتأكد أن النتيجة قابلة للتكرار.")
    print("- هاد التحليل مبني على الكلمات والمعلومات المسجلة فقط؛ ما كيثبتش تعلّماً ذاتياً.")
    print("- عِلسان ما غيبدّلش الكود الأساسي أو قيم النموذج بلا موافقتك.")


