def بحث_مجاني(عبارة):
    """بحث مجاني عبر واجهة ويكيبيديا مع ملخصات نصية نظيفة وروابط واضحة."""
    try:
        import requests
    except ImportError:
        print("مكتبة البحث ناقصة؛ كنثبتوها مجاناً...")
        try:
            subprocess.check_call([sys.executable, "-m", "pip", "install", "-q", "requests"])
            import requests
        except Exception as خطأ:
            print("تعذر تجهيز البحث:", خطأ)
            return []

    المصادر = [
        ("ar.wikipedia.org", "https://ar.wikipedia.org/w/api.php", "ar"),
        ("en.wikipedia.org", "https://en.wikipedia.org/w/api.php", "en"),
    ]
    آخر_خطأ = None
    for اسم_المصدر, رابط_الخدمة, اللغة in المصادر:
        try:
            استجابة = requests.get(
                رابط_الخدمة,
                params={
                    "action": "query", "generator": "search", "gsrsearch": عبارة,
                    "gsrlimit": 8, "gsrnamespace": 0, "prop": "extracts",
                    "exintro": 1, "explaintext": 1, "exsentences": 3,
                    "format": "json", "formatversion": 2, "utf8": 1,
                },
                headers={"User-Agent": "AlsanMoroccan/1.1 (educational project)"},
                timeout=18,
            )
            if استجابة.status_code != 200:
                آخر_خطأ = f"{اسم_المصدر}: رمز الاستجابة {استجابة.status_code}"
                continue
            بيانات = استجابة.json()
            صفحات = بيانات.get("query", {}).get("pages", [])
            نتائج = []
            صفحات = sorted(صفحات, key=lambda x: x.get("index", 999))
            عناوين_مكررة = set()
            for صفحة in صفحات:
                عنوان = str(صفحة.get("title", "")).strip()
                ملخص = re.sub(r"\s+", " ", str(صفحة.get("extract", ""))).strip()
                مفتاح = عنوان.casefold()
                if not عنوان or مفتاح in عناوين_مكررة:
                    continue
                عناوين_مكررة.add(مفتاح)
                if not ملخص:
                    continue
                رابط = "https://" + اسم_المصدر + "/wiki/" + requests.utils.quote(عنوان.replace(" ", "_"), safe="()/:_")
                نتائج.append({"العنوان": عنوان, "الملخص": ملخص[:1200], "الرابط": رابط, "المصدر": اسم_المصدر})
                if len(نتائج) >= 5:
                    break
            if نتائج:
                print(f"المصدر المستعمل: {اسم_المصدر}")
                return نتائج
            آخر_خطأ = f"{اسم_المصدر}: ما لقاتش صفحات فيها ملخصات قابلة للاستعمال."
        except Exception as خطأ:
            آخر_خطأ = f"{اسم_المصدر}: {type(خطأ).__name__}: {خطأ}"
    print("تعذر جلب نتائج قابلة للاستعمال فهاد المحاولة.")
    if آخر_خطأ:
        print("التفاصيل:", آخر_خطأ)
    print("يمكن تعاود المحاولة لاحقاً.")
    return []


def قراءة_ملف_نصي(المسار):
    """قراءة ملفات TXT وMD وPDF، مع تثبيت قارئ PDF المجاني عند الحاجة."""
    المسار = os.path.expanduser(المسار.strip().strip('"').strip("'"))
    if not os.path.isfile(المسار):
        print("ما لقيتش الملف. دخل المسار الصحيح ديالو.")
        return ""
    الامتداد = os.path.splitext(المسار)[1].lower()
    try:
        if الامتداد in (".txt", ".md", ".py", ".csv"):
            with open(المسار, "r", encoding="utf-8-sig") as ملف:
                نص = ملف.read()
        elif الامتداد == ".pdf":
            try:
                from pypdf import PdfReader
            except ImportError:
                subprocess.check_call([sys.executable, "-m", "pip", "install", "-q", "pypdf"])
                from pypdf import PdfReader
            قارئ = PdfReader(المسار)
            نص = "\n".join(صفحة.extract_text() or "" for صفحة in قارئ.pages)
        else:
            print("النسخة الحالية كتدعم TXT وMD وPY وCSV وPDF.")
            return ""
        if not نص.strip():
            print("ما استخرجنا حتى نص؛ يمكن PDF مصوّر ويحتاج OCR.")
            return ""
        return نص
    except Exception as خطأ:
        print("تعذرت قراءة الملف:", خطأ)
        return ""


