def بيع_منتوج(الاسم, الكمية):
    """يبيع كمية، يحدّث المخزون، يسجل العملية، ويحسب الربح أو الخسارة."""
    global مجموع_الأرباح
    if الاسم not in منتوجات:
        print("⚠️ المنتوج غير موجود.")
        return
    if not isinstance(الكمية, int) or الكمية <= 0:
        print("⚠️ الكمية خاصها تكون عدداً صحيحاً أكبر من صفر.")
        return
    بيانات = منتوجات[الاسم]
    if الكمية > بيانات["الكمية"]:
        print("⚠️ المخزون غير كافٍ. المتوفر:", بيانات["الكمية"])
        return
    ثمن_الشراء = بيانات["ثمن_الشراء"]
    ثمن_البيع = بيانات["ثمن_البيع"]
    الربح = (ثمن_البيع - ثمن_الشراء) * الكمية
    بيانات["الكمية"] -= الكمية
    مجموع_الأرباح += الربح
    سجل_المبيعات.append({
        "الوقت": datetime.now().isoformat(timespec="seconds"),
        "المنتوج": الاسم,
        "الكمية": الكمية,
        "ثمن_الشراء_للوحدة": ثمن_الشراء,
        "ثمن_البيع_للوحدة": ثمن_البيع,
        "الربح_أو_الخسارة": الربح,
    })
    print(f"✅ المنتوج: {الاسم}")
    print(f"الكمية المباعة: {الكمية}")
    if الربح > 0:
        print(f"الربح: {الربح:g}")
    elif الربح < 0:
        print(f"الخسارة: {-الربح:g}")
    else:
        print("لا ربح لا خسارة.")
    print(f"المخزون المتبقي: {بيانات['الكمية']}")
    print(f"مجموع الربح/الخسارة الصافي: {مجموع_الأرباح:g}")
    حفظ_البيانات()


